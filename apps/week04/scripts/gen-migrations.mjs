import fs from "node:fs/promises";
import path from "node:path";

// Embeds the allowlisted Patchouli SQL migrations (and the import manifest) into
// a TypeScript module so the Stencil bundle has no import.meta.glob dependency.
const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "vendor/patchouli/src/Patchouli.Infrastructure/migrations");
const files = (await fs.readdir(dir)).filter((f) => f.endsWith(".sql")).sort();
if (!files.length)
  throw new Error(`No SQL migrations found under ${dir}; run pnpm prepare:patchouli`);

let out = "// Generated by scripts/gen-migrations.mjs from vendor/patchouli.\n";
out += "// Do not edit; regenerate with pnpm gen:migrations.\n";
out += "export const MIGRATIONS: Record<string, string> = {\n";
for (const file of files) {
  const sql = await fs.readFile(path.join(dir, file), "utf8");
  out += `  ${JSON.stringify(file)}: ${JSON.stringify(sql)},\n`;
}
out += "};\n\n";
const manifest = JSON.parse(
  await fs.readFile(path.join(root, "vendor/patchouli/manifest.json"), "utf8"),
);
out += `export const PATCHOULI_MANIFEST: Record<string, unknown> = ${JSON.stringify(manifest, null, 2)};\n`;
const target = path.join(root, "src/lib/migrations.generated.ts");
await fs.mkdir(path.dirname(target), { recursive: true });
await fs.writeFile(target, out);
console.log(`Generated ${files.length} migrations into src/lib/migrations.generated.ts`);
